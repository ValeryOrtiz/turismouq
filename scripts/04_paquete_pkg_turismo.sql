-- ============================================================================
-- CUERPO DEL PAQUETE
-- ============================================================================
CREATE OR REPLACE PACKAGE BODY pkg_turismo AS

    -- ------------------------------------------------------------------------
    -- Privado: formato de fecha para los mensajes de error
    -- ------------------------------------------------------------------------
    FUNCTION fmt(p_fecha DATE) RETURN VARCHAR2 IS
    BEGIN
        RETURN TO_CHAR(p_fecha, 'DD/MM/YYYY');
    END fmt;

    -- ========================================================================
    -- fn_valor_estadia
    -- Recorre la estadia noche por noche (desde fecha_in hasta fecha_out - 1).
    -- Para cada noche usa la tarifa de la temporada que la contiene. Para no
    -- consultar la base en cada noche, guarda en variables la temporada
    -- vigente (v_ini..v_fin, v_precio) y solo vuelve a buscar cuando la noche
    -- se sale de ese rango, es decir, cuando la estadia cruza a otra
    -- temporada. Asi una estadia que atraviesa 2 temporadas hace 2 consultas.
    -- Ejemplo: 28/11/2026 -> 03/12/2026 = 5 noches:
    --    28, 29 y 30 nov con la tarifa de 'Temporada media III 2026'
    --    01 y 02 dic   con la tarifa de 'Fin de ano 2026'
    -- ========================================================================
    FUNCTION fn_valor_estadia (
        p_id_habitacion IN HABITACION.habitacion_id%TYPE,
        p_fecha_in      IN DATE,
        p_fecha_out     IN DATE
    ) RETURN NUMBER
    IS
        v_in     DATE := TRUNC(p_fecha_in);
        v_out    DATE := TRUNC(p_fecha_out);
        v_noche  DATE;
        v_ini    DATE;            -- inicio de la temporada vigente
        v_fin    DATE;            -- fin de la temporada vigente (NULL = ninguna aun)
        v_precio NUMBER;          -- precio_noche de la temporada vigente
        v_total  NUMBER := 0;
        v_existe NUMBER;
    BEGIN
        IF v_in IS NULL OR v_out IS NULL THEN
            RAISE_APPLICATION_ERROR(-20002, 'Las fechas de check-in y check-out son obligatorias.');
        END IF;
        IF v_out <= v_in THEN
            RAISE_APPLICATION_ERROR(-20002, 'El check-out (' || fmt(v_out) ||
                ') debe ser posterior al check-in (' || fmt(v_in) || ').');
        END IF;

        SELECT COUNT(*) INTO v_existe FROM HABITACION WHERE habitacion_id = p_id_habitacion;
        IF v_existe = 0 THEN
            RAISE_APPLICATION_ERROR(-20005, 'La habitacion ' || p_id_habitacion || ' no existe.');
        END IF;

        v_noche := v_in;
        WHILE v_noche < v_out LOOP
            -- Cambio de temporada (o primera noche): buscar la tarifa vigente
            IF v_fin IS NULL OR v_noche > v_fin THEN
                BEGIN
                    SELECT t.fecha_inicio, t.fecha_fin, ta.precio_noche
                      INTO v_ini, v_fin, v_precio
                      FROM TEMPORADA t
                      JOIN TARIFA ta ON ta.temporada_id = t.temporada_id
                     WHERE ta.habitacion_id = p_id_habitacion
                       AND v_noche BETWEEN t.fecha_inicio AND t.fecha_fin;
                EXCEPTION
                    WHEN NO_DATA_FOUND THEN
                        RAISE_APPLICATION_ERROR(-20006, 'No hay tarifa para la habitacion ' ||
                            p_id_habitacion || ' la noche del ' || fmt(v_noche) || '.');
                    WHEN TOO_MANY_ROWS THEN
                        RAISE_APPLICATION_ERROR(-20007, 'Hay temporadas cruzadas que contienen la noche del ' ||
                            fmt(v_noche) || '.');
                END;
            END IF;

            v_total := v_total + v_precio;   -- se cobra esta noche
            v_noche := v_noche + 1;          -- siguiente noche
        END LOOP;

        RETURN v_total;
    END fn_valor_estadia;

    -- ========================================================================
    -- fn_valor_reserva: estadia (todas las lineas) + servicios contratados
    -- ========================================================================
    FUNCTION fn_valor_reserva (
        p_reserva_id IN RESERVA.reserva_id%TYPE
    ) RETURN NUMBER
    IS
        v_estadia   NUMBER := 0;
        v_servicios NUMBER;
        v_existe    NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_existe FROM RESERVA WHERE reserva_id = p_reserva_id;
        IF v_existe = 0 THEN
            RAISE_APPLICATION_ERROR(-20009, 'La reserva ' || p_reserva_id || ' no existe.');
        END IF;

        FOR l IN (SELECT habitacion_id, fecha_checkin, fecha_checkout
                    FROM RESERVA_HABITACION
                   WHERE reserva_id = p_reserva_id) LOOP
            v_estadia := v_estadia + fn_valor_estadia(l.habitacion_id, l.fecha_checkin, l.fecha_checkout);
        END LOOP;

        SELECT NVL(SUM(s.precio * rs.cantidad), 0)
          INTO v_servicios
          FROM RESERVA_SERVICIO rs
          JOIN SERVICIO s ON s.servicio_id = rs.servicio_id
         WHERE rs.reserva_id = p_reserva_id;

        RETURN v_estadia + v_servicios;
    END fn_valor_reserva;

    -- ========================================================================
    -- Privado: validaciones comunes de una linea de reserva.
    -- Bloquea la fila de la habitacion (FOR UPDATE) para que dos sesiones no
    -- puedan validar y reservar la misma habitacion al mismo tiempo.
    -- ========================================================================
    PROCEDURE validar_linea (
        p_habitacion_id  IN  NUMBER,
        p_fecha_in       IN  DATE,
        p_fecha_out      IN  DATE,
        p_num_huespedes  IN  NUMBER,
        p_alojamiento_id OUT NUMBER
    )
    IS
        v_capacidad NUMBER;
        v_cruces    NUMBER;
        v_reserva   NUMBER;
    BEGIN
        -- 1) Fechas: checkout anterior o igual al checkin
        IF p_fecha_in IS NULL OR p_fecha_out IS NULL THEN
            RAISE_APPLICATION_ERROR(-20002, 'Las fechas de check-in y check-out son obligatorias.');
        END IF;
        IF TRUNC(p_fecha_out) <= TRUNC(p_fecha_in) THEN
            RAISE_APPLICATION_ERROR(-20002, 'Fechas invalidas: el check-out (' || fmt(p_fecha_out) ||
                ') es anterior o igual al check-in (' || fmt(p_fecha_in) || ').');
        END IF;

        -- 2) Numero de huespedes
        IF p_num_huespedes IS NULL OR p_num_huespedes <= 0 THEN
            RAISE_APPLICATION_ERROR(-20008, 'El numero de huespedes debe ser mayor que cero.');
        END IF;

        -- 3) La habitacion existe (y se bloquea su fila)
        BEGIN
            SELECT capacidad_maxima, alojamiento_id
              INTO v_capacidad, p_alojamiento_id
              FROM HABITACION
             WHERE habitacion_id = p_habitacion_id
               FOR UPDATE;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20005, 'La habitacion ' || p_habitacion_id || ' no existe.');
        END;

        -- 4) Capacidad
        IF p_num_huespedes > v_capacidad THEN
            RAISE_APPLICATION_ERROR(-20003, 'Capacidad excedida: la habitacion ' || p_habitacion_id ||
                ' admite ' || v_capacidad || ' huesped(es) y se pidieron ' || p_num_huespedes || '.');
        END IF;

        -- 5) Disponibilidad: [in, out) se cruza con [ci, co) si in < co y out > ci
        SELECT COUNT(*), MIN(rh.reserva_id)
          INTO v_cruces, v_reserva
          FROM RESERVA_HABITACION rh
          JOIN RESERVA r ON r.reserva_id = rh.reserva_id
         WHERE rh.habitacion_id  = p_habitacion_id
           AND r.estado         <> 'CANCELADA'
           AND rh.fecha_checkin  < TRUNC(p_fecha_out)
           AND rh.fecha_checkout > TRUNC(p_fecha_in);

        IF v_cruces > 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'Habitacion no disponible: la habitacion ' || p_habitacion_id ||
                ' ya esta reservada entre el ' || fmt(p_fecha_in) || ' y el ' || fmt(p_fecha_out) ||
                ' (se cruza con la reserva ' || v_reserva || ').');
        END IF;
    END validar_linea;

    -- ========================================================================
    -- sp_crear_reserva
    -- ========================================================================
    PROCEDURE sp_crear_reserva (
        p_cliente_id    IN  CLIENTE.cliente_id%TYPE,
        p_habitacion_id IN  HABITACION.habitacion_id%TYPE,
        p_fecha_in      IN  DATE,
        p_fecha_out     IN  DATE,
        p_num_huespedes IN  NUMBER,
        p_reserva_id    OUT RESERVA.reserva_id%TYPE,
        p_valor_estadia OUT NUMBER,
        p_estado        IN  RESERVA.estado%TYPE DEFAULT 'PENDIENTE'
    )
    IS
        v_existe NUMBER;
        v_aloj   NUMBER;
        v_valor  NUMBER;
    BEGIN
        IF p_estado IS NULL OR p_estado NOT IN ('PENDIENTE', 'CONFIRMADA') THEN
            RAISE_APPLICATION_ERROR(-20012, 'Una reserva nueva solo puede quedar PENDIENTE o CONFIRMADA.');
        END IF;

        SELECT COUNT(*) INTO v_existe FROM CLIENTE WHERE cliente_id = p_cliente_id;
        IF v_existe = 0 THEN
            RAISE_APPLICATION_ERROR(-20004, 'El cliente ' || p_cliente_id || ' no existe.');
        END IF;

        -- fechas, huespedes, existencia, capacidad y disponibilidad
        validar_linea(p_habitacion_id, p_fecha_in, p_fecha_out, p_num_huespedes, v_aloj);

        -- se calcula ANTES de insertar: si falta una tarifa no queda nada a medias
        v_valor := fn_valor_estadia(p_habitacion_id, p_fecha_in, p_fecha_out);

        INSERT INTO RESERVA (cliente_id, fecha_checkin, fecha_checkout, fecha_reserva, estado)
        VALUES (p_cliente_id, TRUNC(p_fecha_in), TRUNC(p_fecha_out), SYSDATE, p_estado)
        RETURNING reserva_id INTO p_reserva_id;

        INSERT INTO RESERVA_HABITACION (reserva_id, habitacion_id, fecha_checkin,
                                        fecha_checkout, num_huespedes)
        VALUES (p_reserva_id, p_habitacion_id, TRUNC(p_fecha_in), TRUNC(p_fecha_out),
                p_num_huespedes);

        p_valor_estadia := v_valor;
    END sp_crear_reserva;

    -- ========================================================================
    -- sp_agregar_habitacion (reserva de grupo: regla 4 y 5 de la Entrega 1)
    -- ========================================================================
    PROCEDURE sp_agregar_habitacion (
        p_reserva_id    IN  RESERVA.reserva_id%TYPE,
        p_habitacion_id IN  HABITACION.habitacion_id%TYPE,
        p_fecha_in      IN  DATE,
        p_fecha_out     IN  DATE,
        p_num_huespedes IN  NUMBER,
        p_valor_linea   OUT NUMBER
    )
    IS
        v_res_in   DATE;
        v_res_out  DATE;
        v_estado   RESERVA.estado%TYPE;
        v_aloj     NUMBER;
        v_aloj_res NUMBER;
        v_valor    NUMBER;
    BEGIN
        BEGIN
            SELECT fecha_checkin, fecha_checkout, estado
              INTO v_res_in, v_res_out, v_estado
              FROM RESERVA
             WHERE reserva_id = p_reserva_id
               FOR UPDATE;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20009, 'La reserva ' || p_reserva_id || ' no existe.');
        END;

        IF v_estado IN ('CANCELADA', 'COMPLETADA') THEN
            RAISE_APPLICATION_ERROR(-20012, 'No se pueden agregar habitaciones a una reserva ' || v_estado || '.');
        END IF;

        validar_linea(p_habitacion_id, p_fecha_in, p_fecha_out, p_num_huespedes, v_aloj);

        -- Regla 5: la linea debe quedar dentro del rango general de la reserva
        IF TRUNC(p_fecha_in) < v_res_in OR TRUNC(p_fecha_out) > v_res_out THEN
            RAISE_APPLICATION_ERROR(-20002, 'Las fechas de la habitacion deben estar dentro del rango de la reserva (' ||
                fmt(v_res_in) || ' - ' || fmt(v_res_out) || ').');
        END IF;

        -- Regla 4: todas las habitaciones de una reserva son del mismo alojamiento
        SELECT MIN(h.alojamiento_id)
          INTO v_aloj_res
          FROM RESERVA_HABITACION rh
          JOIN HABITACION h ON h.habitacion_id = rh.habitacion_id
         WHERE rh.reserva_id = p_reserva_id;

        IF v_aloj_res IS NOT NULL AND v_aloj_res <> v_aloj THEN
            RAISE_APPLICATION_ERROR(-20010, 'La habitacion ' || p_habitacion_id ||
                ' pertenece a otro alojamiento distinto al de la reserva ' || p_reserva_id || '.');
        END IF;

        v_valor := fn_valor_estadia(p_habitacion_id, p_fecha_in, p_fecha_out);

        INSERT INTO RESERVA_HABITACION (reserva_id, habitacion_id, fecha_checkin,
                                        fecha_checkout, num_huespedes)
        VALUES (p_reserva_id, p_habitacion_id, TRUNC(p_fecha_in), TRUNC(p_fecha_out),
                p_num_huespedes);

        p_valor_linea := v_valor;
    END sp_agregar_habitacion;

    -- ========================================================================
    -- sp_liquidacion_mensual: PROCESO MASIVO CON CURSOR EXPLICITO PARAMETRIZADO
    --
    -- c_liquidacion(cp_inicio, cp_fin, cp_alojamiento) devuelve una fila por
    -- alojamiento con lo que produjo en el mes [cp_inicio, cp_fin):
    --   * noches vendidas DENTRO del mes (una estadia del 30/01 al 02/02
    --     aporta 2 noches a enero y 1 a febrero),
    --   * valor del hospedaje de esas noches con fn_valor_estadia sobre el
    --     tramo recortado al mes (asi tambien respeta los cambios de temporada),
    --   * valor de los servicios de las reservas cuyo check-in cae en el mes.
    -- Solo cuentan reservas CONFIRMADA o COMPLETADA.
    -- Por cada fila se calcula comision y neto, se guarda en
    -- LIQUIDACION_MENSUAL y se imprime el reporte. Reprocesar un mes reemplaza
    -- su liquidacion anterior.
    -- ========================================================================
    PROCEDURE sp_liquidacion_mensual (
        p_anio           IN NUMBER,
        p_mes            IN NUMBER,
        p_alojamiento_id IN NUMBER DEFAULT NULL,
        p_pct_comision   IN NUMBER DEFAULT 0.10
    )
    IS
        CURSOR c_liquidacion (cp_inicio DATE, cp_fin DATE, cp_alojamiento NUMBER) IS
            SELECT a.alojamiento_id,
                   a.nombre_comercial,
                   mu.nombre                       AS municipio,
                   NVL(h.num_reservas, 0)          AS num_reservas,
                   NVL(h.noches, 0)                AS noches,
                   NVL(h.valor_hospedaje, 0)       AS valor_hospedaje,
                   NVL(s.valor_servicios, 0)       AS valor_servicios
              FROM ALOJAMIENTO a
              JOIN MUNICIPIO mu ON mu.municipio_id = a.municipio_id
              LEFT JOIN (
                    SELECT hb.alojamiento_id,
                           COUNT(DISTINCT rh.reserva_id) AS num_reservas,
                           SUM(LEAST(rh.fecha_checkout, cp_fin)
                               - GREATEST(rh.fecha_checkin, cp_inicio)) AS noches,
                           SUM(pkg_turismo.fn_valor_estadia(
                                   rh.habitacion_id,
                                   GREATEST(rh.fecha_checkin, cp_inicio),
                                   LEAST(rh.fecha_checkout, cp_fin))) AS valor_hospedaje
                      FROM RESERVA_HABITACION rh
                      JOIN RESERVA    r  ON r.reserva_id     = rh.reserva_id
                      JOIN HABITACION hb ON hb.habitacion_id = rh.habitacion_id
                     WHERE r.estado IN ('CONFIRMADA', 'COMPLETADA')
                       AND rh.fecha_checkin  < cp_fin
                       AND rh.fecha_checkout > cp_inicio
                     GROUP BY hb.alojamiento_id
                   ) h ON h.alojamiento_id = a.alojamiento_id
              LEFT JOIN (
                    SELECT sv.alojamiento_id,
                           SUM(sv.precio * rs.cantidad) AS valor_servicios
                      FROM RESERVA_SERVICIO rs
                      JOIN SERVICIO sv ON sv.servicio_id = rs.servicio_id
                      JOIN RESERVA  r  ON r.reserva_id   = rs.reserva_id
                     WHERE r.estado IN ('CONFIRMADA', 'COMPLETADA')
                       AND r.fecha_checkin >= cp_inicio
                       AND r.fecha_checkin <  cp_fin
                     GROUP BY sv.alojamiento_id
                   ) s ON s.alojamiento_id = a.alojamiento_id
             WHERE (cp_alojamiento IS NULL OR a.alojamiento_id = cp_alojamiento)
             ORDER BY mu.nombre, a.nombre_comercial;

        r_liq        c_liquidacion%ROWTYPE;
        v_inicio     DATE;
        v_fin        DATE;
        v_bruto      NUMBER;
        v_comision   NUMBER;
        v_neto       NUMBER;
        v_filas      PLS_INTEGER := 0;
        v_tot_noches NUMBER := 0;
        v_tot_bruto  NUMBER := 0;
        v_tot_com    NUMBER := 0;
        v_tot_neto   NUMBER := 0;
    BEGIN
        IF p_anio IS NULL OR p_anio NOT BETWEEN 2000 AND 2100 THEN
            RAISE_APPLICATION_ERROR(-20012, 'Anio invalido: ' || p_anio);
        END IF;
        IF p_mes IS NULL OR p_mes NOT BETWEEN 1 AND 12 THEN
            RAISE_APPLICATION_ERROR(-20012, 'Mes invalido: ' || p_mes);
        END IF;
        IF p_pct_comision IS NULL OR p_pct_comision < 0 OR p_pct_comision >= 1 THEN
            RAISE_APPLICATION_ERROR(-20012, 'La comision debe estar entre 0 y 1 (ej. 0.10).');
        END IF;

        v_inicio := TO_DATE(p_anio || '-' || LPAD(p_mes, 2, '0') || '-01', 'YYYY-MM-DD');
        v_fin    := ADD_MONTHS(v_inicio, 1);           -- limite exclusivo

        -- reproceso: se borra la liquidacion previa del periodo
        DELETE FROM LIQUIDACION_MENSUAL
         WHERE anio = p_anio
           AND mes  = p_mes
           AND (p_alojamiento_id IS NULL OR alojamiento_id = p_alojamiento_id);

        DBMS_OUTPUT.PUT_LINE('LIQUIDACION MENSUAL ' || TO_CHAR(v_inicio, 'YYYY-MM') ||
                             '  (comision ' || TO_CHAR(p_pct_comision * 100) || ' %)');
        DBMS_OUTPUT.PUT_LINE(RPAD('Municipio', 12) || RPAD('Alojamiento', 42) ||
                             LPAD('Res', 5) || LPAD('Noches', 8) ||
                             LPAD('Bruto', 15) || LPAD('Comision', 13) || LPAD('Neto', 15));
        DBMS_OUTPUT.PUT_LINE(RPAD('-', 110, '-'));

        OPEN c_liquidacion(v_inicio, v_fin, p_alojamiento_id);
        LOOP
            FETCH c_liquidacion INTO r_liq;
            EXIT WHEN c_liquidacion%NOTFOUND;

            v_bruto    := r_liq.valor_hospedaje + r_liq.valor_servicios;
            v_comision := ROUND(v_bruto * p_pct_comision, 2);
            v_neto     := v_bruto - v_comision;

            INSERT INTO LIQUIDACION_MENSUAL (alojamiento_id, anio, mes, num_reservas,
                        noches_vendidas, valor_hospedaje, valor_servicios, valor_bruto,
                        pct_comision, valor_comision, valor_neto, fecha_proceso, usuario_proceso)
            VALUES (r_liq.alojamiento_id, p_anio, p_mes, r_liq.num_reservas,
                    r_liq.noches, r_liq.valor_hospedaje, r_liq.valor_servicios, v_bruto,
                    p_pct_comision, v_comision, v_neto, SYSDATE, USER);

            DBMS_OUTPUT.PUT_LINE(RPAD(r_liq.municipio, 12) ||
                                 RPAD(SUBSTR(r_liq.nombre_comercial, 1, 41), 42) ||
                                 LPAD(r_liq.num_reservas, 5) || LPAD(r_liq.noches, 8) ||
                                 LPAD(TO_CHAR(v_bruto, 'FM999,999,999,990'), 15) ||
                                 LPAD(TO_CHAR(v_comision, 'FM99,999,999,990'), 13) ||
                                 LPAD(TO_CHAR(v_neto, 'FM999,999,999,990'), 15));

            v_filas      := v_filas + 1;
            v_tot_noches := v_tot_noches + r_liq.noches;
            v_tot_bruto  := v_tot_bruto + v_bruto;
            v_tot_com    := v_tot_com + v_comision;
            v_tot_neto   := v_tot_neto + v_neto;
        END LOOP;
        CLOSE c_liquidacion;

        COMMIT;

        DBMS_OUTPUT.PUT_LINE(RPAD('-', 110, '-'));
        DBMS_OUTPUT.PUT_LINE(RPAD('TOTAL (' || v_filas || ' alojamientos)', 59) ||
                             LPAD(v_tot_noches, 8) ||
                             LPAD(TO_CHAR(v_tot_bruto, 'FM999,999,999,990'), 15) ||
                             LPAD(TO_CHAR(v_tot_com, 'FM99,999,999,990'), 13) ||
                             LPAD(TO_CHAR(v_tot_neto, 'FM999,999,999,990'), 15));
    EXCEPTION
        WHEN OTHERS THEN
            IF c_liquidacion%ISOPEN THEN
                CLOSE c_liquidacion;
            END IF;
            ROLLBACK;
            RAISE;
    END sp_liquidacion_mensual;

END pkg_turismo;
