-- ============================================================================
-- TurismoUQ - 04_paquete_pkg_turismo.sql            (ENTREGA 2 - entregable 1)
-- Funcion, procedimiento, cursor explicito con parametros y paquete.
-- Ejecutar despues de 01, 02 y 03, como script completo (F5).
-- ----------------------------------------------------------------------------
-- Contenido del paquete PKG_TURISMO
--   fn_valor_estadia(id_habitacion, fecha_in, fecha_out)   valor noche a noche
--   fn_valor_reserva(reserva_id)          estadia de todas las lineas + servicios
--   sp_crear_reserva(...)                 crea reserva de una habitacion
--   sp_agregar_habitacion(...)            agrega otra habitacion a una reserva
--   sp_liquidacion_mensual(anio, mes, ...) liquidacion por alojamiento (cursor)
--
-- Excepciones propias (RAISE_APPLICATION_ERROR + PRAGMA EXCEPTION_INIT):
--   -20001 habitacion no disponible (se cruza con otra reserva activa)
--   -20002 fechas invalidas (checkout anterior o igual al checkin, nulas,
--          o linea fuera del rango de la reserva)
--   -20003 capacidad excedida
--   -20004 cliente no existe          -20005 habitacion no existe
--   -20006 no hay tarifa para una noche de la estadia
--   -20007 temporadas cruzadas (dos temporadas contienen la misma noche)
--   -20008 numero de huespedes invalido
--   -20009 reserva no existe          -20010 habitacion de otro alojamiento
--   -20012 parametro invalido (estado, mes, anio, comision)
--   (-20011 lo usa el disparador de solape del script 05)
--
-- Supuestos (reglas de negocio de la Entrega 1):
--   * Regla 6: se cobra cada noche desde el check-in hasta la vispera del
--     check-out; la noche del check-out no se cobra.
--   * Regla 3: ocupan la habitacion las reservas que NO estan CANCELADA.
--     El dia de check-out queda libre para un nuevo check-in.
--   * Los procedimientos de reserva NO hacen COMMIT: la transaccion la
--     confirma quien los llama (asi se podran combinar con el pago de forma
--     atomica en la Entrega 3). La liquidacion mensual SI hace COMMIT porque
--     es un proceso masivo independiente.
--   * Comision de la plataforma en la liquidacion: 10 % por defecto (supuesto
--     del equipo; es un parametro del procedimiento).
-- ============================================================================

SET SERVEROUTPUT ON SIZE UNLIMITED;
SET DEFINE OFF;

-- ----------------------------------------------------------------------------
-- Tabla donde el proceso masivo deja la liquidacion mensual
-- ----------------------------------------------------------------------------
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE LIQUIDACION_MENSUAL CASCADE CONSTRAINTS PURGE';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;   -- -942: la tabla no existe
END;
/

CREATE TABLE LIQUIDACION_MENSUAL (
    liquidacion_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alojamiento_id   NUMBER NOT NULL,
    anio             NUMBER(4) NOT NULL,
    mes              NUMBER(2) NOT NULL,
    num_reservas     NUMBER NOT NULL,
    noches_vendidas  NUMBER NOT NULL,
    valor_hospedaje  NUMBER(14,2) NOT NULL,
    valor_servicios  NUMBER(14,2) NOT NULL,
    valor_bruto      NUMBER(14,2) NOT NULL,
    pct_comision     NUMBER(5,4) NOT NULL,
    valor_comision   NUMBER(14,2) NOT NULL,
    valor_neto       NUMBER(14,2) NOT NULL,
    fecha_proceso    DATE NOT NULL,
    usuario_proceso  VARCHAR2(128) NOT NULL,
    CONSTRAINT fk_liq_alojamiento FOREIGN KEY (alojamiento_id)
        REFERENCES ALOJAMIENTO(alojamiento_id),
    CONSTRAINT uq_liq_aloj_periodo UNIQUE (alojamiento_id, anio, mes),
    CONSTRAINT ck_liq_mes CHECK (mes BETWEEN 1 AND 12)
);
COMMENT ON TABLE LIQUIDACION_MENSUAL IS 'Resultado del proceso masivo de liquidacion mensual por alojamiento (pkg_turismo.sp_liquidacion_mensual).';

