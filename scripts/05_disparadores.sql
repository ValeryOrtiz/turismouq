SET SERVEROUTPUT ON;
SET DEFINE OFF;

-- ----------------------------------------------------------------------------
-- Limpieza (idempotente)
-- ----------------------------------------------------------------------------
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE AUDITORIA_TARIFA CASCADE CONSTRAINTS PURGE';
EXCEPTION
    WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF;
END;
/
BEGIN
    EXECUTE IMMEDIATE 'DROP SEQUENCE SEQ_AUDITORIA_SENTENCIA';
EXCEPTION
    WHEN OTHERS THEN IF SQLCODE != -2289 THEN RAISE; END IF;
END;
/

-- ============================================================================
-- A) AUDITORIA DE CAMBIOS SOBRE TARIFA (disparador de sentencia)
-- ----------------------------------------------------------------------------
-- Problema: un disparador de sentencia "puro" (sin FOR EACH ROW) se ejecuta
-- una sola vez por sentencia y NO tiene acceso a :OLD ni a :NEW, asi que por
-- si solo no puede saber el valor anterior y el nuevo.
-- Solucion: un COMPOUND TRIGGER (Oracle 11g+). Tiene secciones de sentencia
-- y de fila que comparten variables:
--   BEFORE STATEMENT : una vez por sentencia -> numera la sentencia, toma
--                      quien (usuario BD, usuario SO, equipo, programa) y
--                      cuando (SYSTIMESTAMP).
--   AFTER EACH ROW   : solo copia :OLD y :NEW a una coleccion en memoria.
--   AFTER STATEMENT  : una vez por sentencia -> escribe toda la auditoria
--                      con un solo FORALL.
-- La escritura ocurre a nivel de sentencia: un UPDATE que cambia 300 tarifas
-- hace UNA insercion masiva y todas sus filas quedan con el mismo
-- id_sentencia y la misma fecha_hora. Es el patron clasico "disparador de
-- fila que acumula + disparador de sentencia que escribe", pero en un solo
-- objeto y sin variables globales de paquete.
-- Si la sentencia hace ROLLBACK, la auditoria tambien se deshace: solo queda
-- registro de los cambios que realmente se confirmaron.
-- ============================================================================
CREATE SEQUENCE SEQ_AUDITORIA_SENTENCIA START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE AUDITORIA_TARIFA (
    auditoria_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sentencia    NUMBER        NOT NULL,
    operacion       VARCHAR2(6)   NOT NULL,
    habitacion_id   NUMBER        NOT NULL,
    temporada_id    NUMBER        NOT NULL,
    precio_anterior NUMBER(10,2),
    precio_nuevo    NUMBER(10,2),
    usuario_bd      VARCHAR2(128) NOT NULL,
    usuario_so      VARCHAR2(128),
    equipo          VARCHAR2(128),
    programa        VARCHAR2(128),
    fecha_hora      TIMESTAMP     NOT NULL,
    CONSTRAINT ck_aud_operacion CHECK (operacion IN ('INSERT','UPDATE','DELETE'))
);
-- Sin FK hacia TARIFA a proposito: la auditoria debe sobrevivir aunque la
-- tarifa se borre.
COMMENT ON TABLE AUDITORIA_TARIFA IS 'Auditoria de cambios en TARIFA: quien, cuando, valor anterior y nuevo (trg_tarifa_auditoria).';

CREATE OR REPLACE TRIGGER trg_tarifa_auditoria
FOR INSERT OR UPDATE OR DELETE ON TARIFA
COMPOUND TRIGGER

    TYPE t_fila IS RECORD (
        habitacion_id   NUMBER,
        temporada_id    NUMBER,
        precio_anterior NUMBER,
        precio_nuevo    NUMBER
    );
    TYPE t_filas IS TABLE OF t_fila INDEX BY PLS_INTEGER;

    g_filas        t_filas;
    g_id_sentencia NUMBER;
    g_operacion    VARCHAR2(6);
    g_usuario_bd   VARCHAR2(128);
    g_usuario_so   VARCHAR2(128);
    g_equipo       VARCHAR2(128);
    g_programa     VARCHAR2(128);
    g_momento      TIMESTAMP;

    -- ---------------- una vez, antes de la sentencia ----------------
    BEFORE STATEMENT IS
    BEGIN
        g_filas.DELETE;
        g_id_sentencia := SEQ_AUDITORIA_SENTENCIA.NEXTVAL;
        g_operacion    := CASE WHEN INSERTING THEN 'INSERT'
                               WHEN UPDATING  THEN 'UPDATE'
                               ELSE 'DELETE' END;
        g_usuario_bd   := USER;
        g_usuario_so   := SYS_CONTEXT('USERENV', 'OS_USER');
        g_equipo       := SYS_CONTEXT('USERENV', 'HOST');
        g_programa     := SUBSTR(SYS_CONTEXT('USERENV', 'MODULE'), 1, 128);
        g_momento      := SYSTIMESTAMP;
    END BEFORE STATEMENT;

    -- ---------------- por cada fila: solo se acumula ----------------
    AFTER EACH ROW IS
        i PLS_INTEGER;
    BEGIN
        -- un UPDATE que deja el mismo precio no es un cambio: no se registra
        IF NOT (UPDATING
                AND :OLD.precio_noche  = :NEW.precio_noche
                AND :OLD.habitacion_id = :NEW.habitacion_id
                AND :OLD.temporada_id  = :NEW.temporada_id) THEN
            i := g_filas.COUNT + 1;
            g_filas(i).habitacion_id   := NVL(:NEW.habitacion_id, :OLD.habitacion_id);
            g_filas(i).temporada_id    := NVL(:NEW.temporada_id,  :OLD.temporada_id);
            g_filas(i).precio_anterior := :OLD.precio_noche;   -- NULL en INSERT
            g_filas(i).precio_nuevo    := :NEW.precio_noche;   -- NULL en DELETE
        END IF;
    END AFTER EACH ROW;

    -- ---------------- una vez, despues de la sentencia ----------------
    AFTER STATEMENT IS
    BEGIN
        FORALL i IN 1 .. g_filas.COUNT
            INSERT INTO AUDITORIA_TARIFA (id_sentencia, operacion, habitacion_id,
                        temporada_id, precio_anterior, precio_nuevo, usuario_bd,
                        usuario_so, equipo, programa, fecha_hora)
            VALUES (g_id_sentencia, g_operacion, g_filas(i).habitacion_id,
                    g_filas(i).temporada_id, g_filas(i).precio_anterior,
                    g_filas(i).precio_nuevo, g_usuario_bd, g_usuario_so,
                    g_equipo, g_programa, g_momento);
        g_filas.DELETE;
    END AFTER STATEMENT;

END trg_tarifa_auditoria;
/
SHOW ERRORS TRIGGER trg_tarifa_auditoria;

-- ============================================================================
-- B) SIN SOLAPES DE HABITACION (disparador de fila)
-- ----------------------------------------------------------------------------
-- BEFORE INSERT ... FOR EACH ROW sobre RESERVA_HABITACION: antes de registrar
-- cada linea busca otra linea ACTIVA (reserva no CANCELADA) de la misma
-- habitacion cuyas fechas se crucen. Dos rangos [ci, co) se cruzan si
--     nuevo.checkin < otra.checkout  Y  nuevo.checkout > otra.checkin
-- (el dia de check-out queda libre: salir el 5 y entrar el 5 si se permite).
-- Si la linea nueva pertenece a una reserva CANCELADA no se valida, porque
-- no ocupa la habitacion.
--
-- Es la ultima linea de defensa: sp_crear_reserva ya valida lo mismo
-- (-20001), pero el disparador impide el solape aunque alguien inserte
-- directamente en la tabla, sin pasar por el paquete (-20011).
--
-- Tabla mutante: un disparador de fila no puede consultar su propia tabla
-- cuando la sentencia afecta varias filas (ORA-04091). Oracle SI lo permite
-- cuando el disparo viene de un INSERT ... VALUES de una sola fila, que es
-- como inserta toda la capa PL/SQL. Para que nadie se salte la regla por
-- UPDATE, cambiar la habitacion o las fechas de una linea existente queda
-- prohibido (-20013): un cambio de fechas se hace cancelando y creando otra
-- reserva, para que pase por todas las validaciones.
-- ============================================================================
CREATE OR REPLACE TRIGGER trg_reshab_no_solape
BEFORE INSERT OR UPDATE OF habitacion_id, fecha_checkin, fecha_checkout
ON RESERVA_HABITACION
FOR EACH ROW
DECLARE
    v_estado_nueva RESERVA.estado%TYPE;
    v_reserva_otra NUMBER;
    v_ci_otra      DATE;
    v_co_otra      DATE;
BEGIN
    IF UPDATING THEN
        IF :OLD.habitacion_id  <> :NEW.habitacion_id
        OR :OLD.fecha_checkin  <> :NEW.fecha_checkin
        OR :OLD.fecha_checkout <> :NEW.fecha_checkout THEN
            RAISE_APPLICATION_ERROR(-20013, 'No se permite cambiar la habitacion ni las fechas de una ' ||
                'linea de reserva. Cancele la reserva y cree una nueva.');
        END IF;
    ELSE
        -- estado de la reserva a la que pertenece la nueva linea
        BEGIN
            SELECT estado INTO v_estado_nueva
              FROM RESERVA
             WHERE reserva_id = :NEW.reserva_id;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                v_estado_nueva := NULL;   -- la FK rechazara la fila despues
        END;

        IF v_estado_nueva IS NOT NULL AND v_estado_nueva <> 'CANCELADA' THEN
            SELECT MIN(rh.reserva_id), MIN(rh.fecha_checkin), MIN(rh.fecha_checkout)
              INTO v_reserva_otra, v_ci_otra, v_co_otra
              FROM RESERVA_HABITACION rh
              JOIN RESERVA r ON r.reserva_id = rh.reserva_id
             WHERE rh.habitacion_id  = :NEW.habitacion_id
               AND r.estado         <> 'CANCELADA'
               AND rh.fecha_checkin  < :NEW.fecha_checkout
               AND rh.fecha_checkout > :NEW.fecha_checkin;

            IF v_reserva_otra IS NOT NULL THEN
                RAISE_APPLICATION_ERROR(-20011, 'Solape de reservas: la habitacion ' || :NEW.habitacion_id ||
                    ' ya esta ocupada por la reserva ' || v_reserva_otra || ' (' ||
                    TO_CHAR(v_ci_otra, 'DD/MM/YYYY') || ' - ' || TO_CHAR(v_co_otra, 'DD/MM/YYYY') ||
                    ') y la nueva linea pide ' || TO_CHAR(:NEW.fecha_checkin, 'DD/MM/YYYY') ||
                    ' - ' || TO_CHAR(:NEW.fecha_checkout, 'DD/MM/YYYY') || '.');
            END IF;
        END IF;
    END IF;
END trg_reshab_no_solape;
/
SHOW ERRORS TRIGGER trg_reshab_no_solape;

-- Estado de los disparadores (deben quedar ENABLED / VALID)
SELECT t.trigger_name, t.trigger_type, t.triggering_event, t.table_name, t.status, o.status AS compilacion
FROM   user_triggers t
JOIN   user_objects  o ON o.object_name = t.trigger_name AND o.object_type = 'TRIGGER'
WHERE  t.trigger_name IN ('TRG_TARIFA_AUDITORIA', 'TRG_RESHAB_NO_SOLAPE');
